// Reads the current-color icon SVGs from the copied asset library and bakes
// them into a plain JS map so <Icon> never touches the filesystem at
// runtime (which would break when the component is pulled into a client
// bundle). Re-run via `pnpm generate:icons` if icons are added/changed.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ICONS_DIR = join(
  __dirname,
  "..",
  "public",
  "assets",
  "exotic",
  "icons",
  "current-color"
);
const OUT_DIR = join(__dirname, "..", "src", "generated");
const OUT_FILE = join(OUT_DIR, "icon-map.ts");

const files = readdirSync(ICONS_DIR).filter((f) => f.endsWith(".svg"));

const entries = files.map((file) => {
  const name = file.replace(/\.svg$/, "");
  const raw = readFileSync(join(ICONS_DIR, file), "utf8");
  const cleaned = raw
    .replace(/<title>.*?<\/title>/, "")
    .replace("<svg ", '<svg aria-hidden="true" focusable="false" ');
  return [name, cleaned];
});

mkdirSync(OUT_DIR, { recursive: true });

const body = entries
  .map(([name, svg]) => `  ${JSON.stringify(name)}: ${JSON.stringify(svg)},`)
  .join("\n");

writeFileSync(
  OUT_FILE,
  `// Generated by scripts/generate-icons.mjs — do not edit by hand.\nexport const ICON_MAP: Record<string, string> = {\n${body}\n};\n`,
  "utf8"
);

console.log(`Wrote ${entries.length} icons to ${OUT_FILE}`);
